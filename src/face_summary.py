"""Generate reviewer tables from the face validation and audited final records."""
import argparse
from pathlib import Path

import numpy as np

from src.experiment import read_json, write_json


def rows_macro(name, rows):
    return "\n".join([rf"\newcommand{{\{name}}}{{%", *[
        " & ".join(cells) + r" \\" for cells in rows
    ], "}"])


def write_tables(results, target):
    selection = read_json(results / "selection.json")
    cfg = selection["config"]
    validation = read_json(results / "validation.json")
    runs = read_json(results / "final.json")["runs"]
    fractions = cfg["fractions"]
    rank = cfg["primary_rank"]
    methods = ("Pixels", "PCA", "LDA", "No smoothness", "RSSPCA")
    summary, recognition, reconstruction, tuning = [], [], [], []
    for method in methods:
        k = 256 if method == "Pixels" else rank
        performance = []
        for fraction in fractions:
            grouped = [r for r in runs if (r["method"], r["fraction"], r["rank"]) ==
                       (method, fraction, k)]
            scores = 100 * np.array([r["accuracy"] for r in grouped])
            result = {
                "method": method, "rank": k, "fraction": fraction,
                "accuracy_mean_pct": float(scores.mean()),
                "accuracy_sd_pp": float(scores.std(ddof=1)) if len(scores)>1 else None,
                "macro_f1_pct": 100 * float(np.mean([r["macro_f1"] for r in grouped])),
                "pixel_mse": float(np.mean([r["mean_mse"] for r in grouped]))
                if grouped[0]["mean_mse"] is not None else None,
            }
            summary.append(result)
            performance.append(result)
        cells = [method, str(k)]
        for record in performance:
            mean, sd = record["accuracy_mean_pct"], record["accuracy_sd_pp"]
            cells.append(f"{mean:.2f}" if sd is None else rf"{mean:.2f}\,$\pm$\,{sd:.2f}")
        cells.append(f"{performance[-1]['macro_f1_pct']:.2f}")
        recognition.append(cells)
        if performance[-1]["pixel_mse"] is not None:
            reconstruction.append([method, *[f"{record['pixel_mse']*1000:.3f}"
                                             for record in performance]])
    for eta in cfg["eta"]:
        for gamma in cfg["gamma"]:
            scores = [100 * next(r["accuracy"] for r in validation
                                 if (r["eta"], r["gamma"], r["fraction"]) ==
                                 (eta, gamma, fraction)) for fraction in fractions]
            tuning.append([f"{eta:g}", f"{gamma:g}", *[f"{a:.2f}" for a in scores],
                           f"{np.mean(scores):.2f}"])
    text = "\n".join([
        "% Generated by python -m src.face_summary.",
        rows_macro("facemetrows", recognition),
        rows_macro("facemsrows", reconstruction),
        rows_macro("facevalrows", tuning),
    ]) + "\n"
    target.write_text(text, encoding="utf-8")
    write_json(results / "summary.json", summary)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results/faces"))
    parser.add_argument("--table", type=Path, default=Path("report/face_tables.tex"))
    args = parser.parse_args()
    write_tables(args.results, args.table)


if __name__ == "__main__":
    main()
