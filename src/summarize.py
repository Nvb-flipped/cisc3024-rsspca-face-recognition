"""Independently check archived predictions and emit the report's central numbers."""
import argparse
import itertools
from collections import defaultdict
from pathlib import Path

import numpy as np

from src.data import load_partition
from src.experiment import read_json, write_json


def verify_partitions(cfg, results, data):
    x, y, sha = load_partition(data, "tra")
    _, test_y, test_sha = load_partition(data, "tes")
    selection = read_json(results / "selection.json")
    final = read_json(results / "final.json")
    assert sha == selection["development_sha256"] and test_sha == final["test_sha256"]
    splits = read_json(results / "splits.json")
    counts = np.zeros(len(y), dtype=int)
    with np.load(results / "validation_masks.npz") as masks:
        for fold in splits["development_folds"]:
            train, valid = np.array(fold["fit"]), np.array(fold["validation"])
            np.testing.assert_array_equal(np.sort(np.r_[train, valid]), np.arange(len(y)))
            counts[valid] += 1
            assert np.all(np.bincount(y[valid], minlength=10) > 0)
            for i, frac in enumerate(cfg["fractions"]):
                prefix = f"f{fold['fold']}_r{i}"
                rows = masks[f"{prefix}_rows"]
                assert len(np.unique(rows)) == int(frac * len(train))
                assert np.isin(rows, train).all()
    np.testing.assert_array_equal(counts, np.ones(len(x), dtype=int))
    np.testing.assert_array_equal(splits["official_test_indices"], np.arange(len(test_y)))
    with np.load(results / "predictions.npz") as archive:
        np.testing.assert_array_equal(test_y, archive["y"])
        for record in final["runs"]:
            pred = archive[record["prediction_key"]]
            assert len(pred) == len(test_y) and ((0 <= pred) & (pred <= 9)).all()
            matrix = np.zeros((10, 10), dtype=int)
            np.add.at(matrix, (test_y, pred), 1)
            tp = matrix.diagonal()
            np.testing.assert_array_equal(record["confusion"], matrix)
            np.testing.assert_allclose(
                [record["accuracy"], record["balanced_accuracy"], record["macro_f1"]],
                [np.mean(pred == test_y), np.mean(tp / matrix.sum(axis=1)),
                 np.mean(2 * tp / (matrix.sum(axis=0) + matrix.sum(axis=1)))],
                rtol=1e-13, atol=0,
            )
    return final["runs"]


def summarize(rows):
    groups = {}
    for key, entries in itertools.groupby(
        sorted(rows, key=lambda r: (r["method"], r["fraction"], r["rank"])),
        key=lambda r: (r["method"], r["fraction"], r["rank"]),
    ):
        groups[key] = sorted(entries, key=lambda r: r["seed"])
    stats = []
    for (method, fraction, rank), entries in groups.items():
        block = {"method": method, "fraction": fraction, "rank": rank, "n": len(entries)}
        for key in ("accuracy", "balanced_accuracy", "macro_f1", "unit_direction_energy",
                    "near_zero_fraction", "fit_seconds", "predict_seconds"):
            values = np.array([entry[key] for entry in entries])
            block[key] = {"mean": float(values.mean()), "median": float(np.median(values)),
                          "sd": float(values.std(ddof=1)) if len(values) > 1 else None}
        block["capped_components"] = sum(r["capped_components"] for r in entries)
        stats.append(block)
    contrasts = []
    for fraction in (0., .25, .5):
        rss = groups["RSSPCA", fraction, 8]
        for comparison in ("PCA", "LDA", "No smoothness"):
            other = groups[comparison, fraction, 8]
            delta = [100 * (a["accuracy"] - b["accuracy"])
                     for a, b in zip(rss, other, strict=True) if a["seed"] == b["seed"]]
            assert len(delta) == len(rss)
            contrasts.append({
                "fraction": fraction, "contrast": comparison, "pp": delta,
                "mean_pp": float(np.mean(delta)), "range_pp": [min(delta), max(delta)],
            })
    return {"aggregate": stats, "paired_rsspca_minus": contrasts}


def table(stats):
    items = {(r["method"], r["fraction"], r["rank"]): r for r in stats["aggregate"]}
    rows = ["% Generated by python -m src.summarize.", r"\newcommand{\maintablerows}{%"]

    def format_metric(record, key):
        metric = record[key]
        text = f"{100*metric['mean']:.2f}"
        if metric["sd"] is not None:
            text += rf"\,$\pm$\,{100*metric['sd']:.2f}"
        return text

    for method in ("Pixels", "PCA", "LDA", "No smoothness", "RSSPCA"):
        rank = 64 if method == "Pixels" else 8
        reports = [items[method, f, rank] for f in (0., .25, .5)]
        fields = [method, str(rank), *(format_metric(r, "accuracy") for r in reports),
                  f"{100*reports[-1]['balanced_accuracy']['mean']:.2f}",
                  f"{100*reports[-1]['macro_f1']['mean']:.2f}"]
        rows.append(" & ".join(fields) + r" \\")
    return "\n".join([*rows, "}"]) + "\n"


def validation_table(records, cfg):
    grouped = defaultdict(list)
    for record in records:
        grouped[record["eta"], record["gamma"]].append(record["accuracy"])
    rows = [r"\newcommand{\validationrows}{%"]
    expected_count = len(cfg["fold_corruption_seeds"]) * len(cfg["fractions"])
    for eta in cfg["eta"]:
        fields = [f"{eta:g}"]
        for gamma in (0, *cfg["gamma"]):
            scores = grouped[eta, gamma]
            if len(scores) != expected_count:
                raise ValueError(f"Incomplete validation grid at eta={eta}, gamma={gamma}")
            fields.append(f"{100*np.mean(scores):.2f}")
        rows.append(" & ".join(fields) + r" \\")
    return "\n".join([*rows, "}"]) + "\n"


def class_table(runs, cfg):
    rows = [r"\newcommand{\classrecallrows}{%"]
    for method in ("PCA", "LDA", "No smoothness", "RSSPCA"):
        matrices = np.array([
            row["confusion"] for row in runs
            if row["method"] == method and row["rank"] == cfg["primary_rank"]
            and row["fraction"] == max(cfg["fractions"])
        ])
        recall = 100 * np.diagonal(matrices, axis1=1, axis2=2) / matrices.sum(axis=2)
        fields = [method]
        for digit in (8, 9):
            scores = recall[:, digit]
            fields.extend([f"{scores.mean():.2f}", f"{scores.min():.2f}--{scores.max():.2f}"])
        rows.append(" & ".join(fields) + r" \\")
    return "\n".join([*rows, "}"]) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--data", type=Path, default=Path("data"))
    parser.add_argument("--write-tex", type=Path, default=Path("report/results_table.tex"))
    args = parser.parse_args()
    cfg = read_json("configs/study.json")
    runs = verify_partitions(cfg, args.results, args.data)
    summary = summarize(runs)
    write_json(args.results / "summary.json", summary)
    args.write_tex.parent.mkdir(parents=True, exist_ok=True)
    validation = read_json(args.results / "validation.json")
    args.write_tex.write_text(table(summary) + validation_table(validation, cfg) +
                             class_table(runs, cfg), encoding="utf-8")
    print(f"Verified {len(runs)} runs against archived predictions and official labels.")


if __name__ == "__main__":
    main()
